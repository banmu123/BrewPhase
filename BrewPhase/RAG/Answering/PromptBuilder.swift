import Foundation

/// 提示词。
///
/// 三条纪律，都是为了让「有依据」这件事成为默认行为而不是运气：
/// 1. **只能依据资料**——本地小模型一旦被允许用常识补充，它就会开始编日期和克数；
/// 2. **必须标引用**——编号是回答和证据之间唯一的连接，没有它，用户没法判断
///    这句话是查出来的还是编的；
/// 3. **证据不足要直说**——这是唯一能让这个功能在数据不足时仍然可信的做法。
///
/// 提示词本身是**界面语言的文本**，所以逐句走 `L()`：中文界面下模型看到中文说明，
/// 英文界面下看到英文说明，回答的语言也就跟着界面走了。
enum PromptBuilder {

    static func system() -> String {
        [
            L("你是 BrewPhase 里的助手，帮用户看懂他自己的咖啡记录。用户是喝手冲的人，不是工程师。"),
            L("下面会给你两部分资料：一部分是用户自己的豆子、冲煮和风味记录，一部分是 BrewPhase 自带的咖啡常识。"),
            L("只依据这些资料回答。资料里没有的数字、日期、克数、分数，一个都不要写。"),
            L("每条资料前面有一个编号，例如 [1]。你的回答里用到哪一条，就在那句话末尾写上它的编号。"),
            L("要分清来源：说用户自己做过什么、喝到什么，只能引用「用户自己的记录」那部分；说通用的咖啡常识，才引用知识库那部分。"),
            L("如果资料不足以回答，就直接说找不到，并说清缺什么。不要用常识补一个听起来合理的答案。"),
            L("回答直接给结论，三到五句话。不要复述资料原文，也不要解释你是怎样检索的。"),
            L("回答的语言要和上面这些说明一致。"),
        ].joined(separator: "\n")
    }

    static func user(context: BuiltContext) -> String {
        [
            L("问题：%@", context.question),
            "",
            context.rendered,
        ].joined(separator: "\n")
    }
}
